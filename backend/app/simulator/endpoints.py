import random
import time
from datetime import datetime, timezone
from typing import Optional, Tuple
from ..schemas.model import ModelConfig
from ..schemas.request import ExecutionAttempt
from ..estimator.signals import count_tokens

def generate_mock_response(model: ModelConfig, prompt: str, in_tokens: int, out_tokens: int) -> str:
    """
    Generates realistic, domain-aware simulated responses matching the model tier.
    """
    prompt_snippet = prompt[:80].strip().replace("\n", " ")
    
    tier_qualifiers = {
        1: "concise direct answer via lightweight extraction",
        2: "structured explanation with clear key points",
        3: "deep balanced analysis with code/step breakdown",
        5: "comprehensive frontier synthesis with formal evaluation & edge cases"
    }
    qualifier = tier_qualifiers.get(model.capability, "standard AI generation")
    
    # Domain specific responses
    p_lower = prompt.lower()
    if any(k in p_lower for k in ["python", "code", "function", "debug", "palindrome", "pointer"]):
        content = (
            f"Here is the verified solution tailored for: \"{prompt_snippet}...\":\n\n"
            f"```python\n"
            f"# Generated by {model.name} ({model.provider})\n"
            f"def solution():\n"
            f"    \"\"\"{qualifier}\"\"\"\n"
            f"    data = [x for x in range(10) if x % 2 == 0]\n"
            f"    return {{'status': 'optimal', 'result': data}}\n"
            f"```\n"
            f"Execution verified under {model.name} capabilities."
        )
    elif any(k in p_lower for k in ["contract", "legal", "liability", "clause"]):
        content = (
            f"### Legal Clause Analysis [{model.name}]\n"
            f"- **Scope**: Comprehensive liability audit on \"{prompt_snippet}...\".\n"
            f"- **Risk Assessment**: Indemnification thresholds identified under standard commercial covenants.\n"
            f"- **Recommendation**: Incorporate mutual limitation caps and severance terms.\n"
            f"Generated with high-capability tier {model.capability} reasoning."
        )
    else:
        content = (
            f"**Answer from {model.name} ({qualifier}):**\n\n"
            f"In response to your query regarding \"{prompt_snippet}...\":\n"
            f"1. Core principle is validated across standard benchmarks.\n"
            f"2. Optimization metrics confirm high fidelity output.\n"
            f"3. All contextual boundaries satisfied within {model.context_window:,} tokens."
        )
        
    return content

def execute_model_call(
    model: ModelConfig,
    prompt: str,
    max_latency_ms: Optional[float],
    estimated_attempt_cost: float,
    attempt_number: int,
    test_seed: Optional[int] = None
) -> Tuple[ExecutionAttempt, Optional[str]]:
    """
    Executes a simulated call to the model endpoint.
    Respects:
      - Force-fail toggle
      - Force-slow toggle
      - Failure probability
      - Artificial delay and jitter
      - Strict runtime latency limit enforcement
    """
    start_dt = datetime.now(timezone.utc)
    start_iso = start_dt.isoformat()
    
    rng = random.Random(test_seed + attempt_number if test_seed is not None else None)
    
    # Determine simulated latency
    jitter = rng.uniform(-10.0, 15.0)
    simulated_latency = max(20.0, model.latency_ms + model.artificial_delay_ms + jitter)
    
    # Check Force-Slow toggle
    if model.force_slow:
        # Force it to exceed max latency if set, or inject a significant delay
        if max_latency_ms is not None:
            simulated_latency = max(simulated_latency, max_latency_ms + rng.uniform(50.0, 150.0))
        else:
            simulated_latency = simulated_latency + 2500.0

    # Sleep a tiny fraction in real wall-clock to ensure measurable elapsed time, but keep response snappy
    # For UI responsiveness, we simulate the number without freezing the thread for 2 full seconds unless running tests
    observed_latency = round(simulated_latency, 1)
    
    end_dt = datetime.now(timezone.utc)
    end_iso = end_dt.isoformat()

    # 1. Force Fail check
    if model.force_fail:
        attempt = ExecutionAttempt(
            model_id=model.id,
            model_name=model.name,
            attempt_number=attempt_number,
            start_time=start_iso,
            end_time=end_iso,
            observed_latency_ms=observed_latency,
            success=False,
            error_reason="FORCE_FAIL: Always-fail toggle is active for this model.",
            estimated_attempt_cost=estimated_attempt_cost
        )
        return attempt, None

    # 2. Random failure rate check
    if model.failure_rate > 0.0:
        roll = rng.random()
        if roll < model.failure_rate:
            attempt = ExecutionAttempt(
                model_id=model.id,
                model_name=model.name,
                attempt_number=attempt_number,
                start_time=start_iso,
                end_time=end_iso,
                observed_latency_ms=observed_latency,
                success=False,
                error_reason=f"RANDOM_FAULT: Transient error occurred (configured failure rate {int(model.failure_rate * 100)}%).",
                estimated_attempt_cost=estimated_attempt_cost
            )
            return attempt, None

    # 3. Latency cap enforcement at runtime (Section 4 Step F)
    # The routing system must NOT claim that a request satisfied its latency limit if observed execution exceeded it.
    if max_latency_ms is not None and observed_latency > max_latency_ms:
        attempt = ExecutionAttempt(
            model_id=model.id,
            model_name=model.name,
            attempt_number=attempt_number,
            start_time=start_iso,
            end_time=end_iso,
            observed_latency_ms=observed_latency,
            success=False,
            error_reason=f"LATENCY_LIMIT_EXCEEDED_AT_RUNTIME: Observed latency {observed_latency}ms exceeded maximum permitted limit of {max_latency_ms}ms.",
            estimated_attempt_cost=estimated_attempt_cost
        )
        return attempt, None

    # Successful response
    in_tokens = count_tokens(prompt)
    response_text = generate_mock_response(model, prompt, in_tokens, 500)
    
    attempt = ExecutionAttempt(
        model_id=model.id,
        model_name=model.name,
        attempt_number=attempt_number,
        start_time=start_iso,
        end_time=end_iso,
        observed_latency_ms=observed_latency,
        success=True,
        error_reason=None,
        estimated_attempt_cost=estimated_attempt_cost
    )
    return attempt, response_text
